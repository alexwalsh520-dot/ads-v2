-- ─────────────────────────────────────────────────────────────────────────
-- RLS. Every one of these tables is written and read by the service-role key
-- from server code only, which bypasses RLS. Turning RLS on with no policy is
-- therefore the correct posture: the app keeps working and the anon key —
-- which ships to the browser — can read nothing.
-- ─────────────────────────────────────────────────────────────────────────
do $$
declare t text;
begin
  foreach t in array array[
    'ads_meta_insights_daily','ads_keyword_events','ghl_appointments','sales_tracker_rows',
    'manychat_contact_links','manychat_origin_checks','organic_keywords','registry_keywords',
    'ad_creative_image','person_context','fx_rates','adsv2_meta','adsv2_dm_facts',
    'adsv2_booking_facts','adsv2_sale_facts','adsv2_booking_resolutions','adsv2_sale_resolutions',
    'adsv2_budget_snapshots','adsv2_window_snapshots','adsv2_sync_runs','adsv2_alerts',
    'app_users','public_share_links'
  ] loop
    execute format('alter table public.%I enable row level security', t);
  end loop;
end $$;

-- Seed the version counter so the first sync has something to bump.
insert into public.adsv2_meta (key, value)
values ('data_version', '0'::jsonb)
on conflict (key) do nothing;
