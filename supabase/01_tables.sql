-- ADS V2 — TABLES
--
-- Run this FIRST, then 02_functions.sql.
-- Everything here is idempotent: running it twice is safe and changes nothing.
--
-- Two groups of tables:
--   INPUT tables  — filled by the ingestion jobs (Meta, ManyChat, GHL, sales sheet).
--   adsv2_* tables — owned by Ads V2 itself. The sync rebuilds them; never hand-edit.
-- ═══════════════════════════════════════════════════════════════════════════

create extension if not exists pgcrypto;

-- ─────────────────────────────────────────────────────────────────────────
-- INPUT: Meta ad spend, one row per ad per day.
-- Filled by /api/cron/meta-spend-sync.
-- The reporting_timezone stamp inside raw_payload is load-bearing: Ads V2 only
-- counts rows pulled in America/New_York, so a day means the same thing for
-- every creator no matter what timezone their ad account bills in.
-- ─────────────────────────────────────────────────────────────────────────
create table if not exists public.ads_meta_insights_daily (
  id uuid not null default gen_random_uuid(),
  client_key text not null,
  client_name text not null,
  ad_account_id text not null,
  account_timezone text,
  campaign_id text,
  campaign_name text,
  adset_id text,
  adset_name text,
  ad_id text not null,
  ad_name text,
  keyword_raw text,
  keyword_normalized text,
  date date not null,
  spend_cents integer not null default 0,
  impressions integer not null default 0,
  link_clicks integer not null default 0,
  raw_payload jsonb,
  synced_at timestamptz default now(),
  created_at timestamptz default now(),
  ad_effective_status text,
  ad_configured_status text,
  campaign_effective_status text,
  campaign_configured_status text,
  constraint ads_meta_insights_daily_pkey primary key (id),
  constraint ads_meta_insights_daily_client_key_ad_id_date_key unique (client_key, ad_id, date)
);
create index if not exists idx_ads_meta_insights_client_date on public.ads_meta_insights_daily (client_key, date desc);
